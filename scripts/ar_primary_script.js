// SORTING GAME
// ==========================================
// Lists that need to be reordered
// Using jquery-ui sortable style or simple up/down buttons?
// Native Drag/Drop sort is complex for touch without lib.
// Let's implement simple "Click to select, Click to swap" or Up/Down arrows.
// Up/Down arrows are easiest for accessibility and simple impl.

function initSorting(containerId) {
    const list = document.querySelector(`#${containerId} .sortable-list`);
    if(!list) return;
    
    // Add controls to each item if not present
    const items = list.querySelectorAll('li');
    items.forEach(item => {
        if(!item.querySelector('.sort-controls')) {
            const controls = document.createElement('div');
            controls.className = 'sort-controls';
            controls.innerHTML = `
                <button class="up-btn">▲</button>
                <button class="down-btn">▼</button>
            `;
            item.appendChild(controls);
            
            controls.querySelector('.up-btn').onclick = () => {
                const prev = item.previousElementSibling;
                if(prev) list.insertBefore(item, prev);
            };
            controls.querySelector('.down-btn').onclick = () => {
                const next = item.nextElementSibling;
                if(next) list.insertBefore(next, item);
            };
        }
    });
}

function checkSorting(containerId) {
    const list = document.querySelector(`#${containerId} .sortable-list`);
    const items = list.querySelectorAll('li');
    let isCorrect = true;
    
    items.forEach((item, index) => {
        if(parseInt(item.dataset.order) !== index + 1) {
            isCorrect = false;
            item.classList.add('wrong');
        } else {
            item.classList.remove('wrong');
            item.classList.add('correct');
        }
    });
    
    showFeedback(`feedback-${containerId}`, isCorrect, isCorrect ? "ترتيب صحيح! ممتاز." : "الترتيب غير صحيح.");
}

