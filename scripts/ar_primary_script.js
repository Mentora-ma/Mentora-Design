// DRAG AND DROP
// ==========================================
/*
Expected Structure:
<div id="dd1" class="drag-drop-container">
   <div class="source-container">
      <div class="draggable-item" draggable="true" data-target="zone1">Item</div>
   </div>
   <div class="target-container">
      <div class="drop-zone" data-zone="zone1">Zone 1</div>
   </div>
</div>
*/

function initDragDrop(containerId) {
    const container = document.getElementById(containerId);
    if (!container) return;

    const draggables = container.querySelectorAll('.draggable-item');
    const droppables = container.querySelectorAll('.drop-zone');

    draggables.forEach(draggable => {
        draggable.addEventListener('dragstart', () => {
            draggable.classList.add('dragging');
        });

        draggable.addEventListener('dragend', () => {
            draggable.classList.remove('dragging');
        });
        
        // Touch support for mobile
        draggable.addEventListener('touchstart', handleTouchStart, {passive: false});
        draggable.addEventListener('touchmove', handleTouchMove, {passive: false});
        draggable.addEventListener('touchend', handleTouchEnd);
    });

    droppables.forEach(zone => {
        zone.addEventListener('dragover', e => {
            e.preventDefault();
            zone.classList.add('drag-over');
        });
        
        zone.addEventListener('dragleave', () => {
             zone.classList.remove('drag-over');
        });

        zone.addEventListener('drop', e => {
            e.preventDefault();
            zone.classList.remove('drag-over');
            const draggable = container.querySelector('.dragging');
            if(draggable) {
                zone.appendChild(draggable);
            }
        });
    });

    // Simple Touch Logic (Fallback)
    let activeTouchElement = null;
    let touchOffsetX = 0;
    let touchOffsetY = 0;
    let originalParent = null;

    function handleTouchStart(e) {
        activeTouchElement = e.target.closest('.draggable-item');
        if(!activeTouchElement) return;
        e.preventDefault(); // prevent scrolling
        const touch = e.touches[0];
        const rect = activeTouchElement.getBoundingClientRect();
        touchOffsetX = touch.clientX - rect.left;
        touchOffsetY = touch.clientY - rect.top;
        originalParent = activeTouchElement.parentElement;
        
        activeTouchElement.style.position = 'absolute';
        activeTouchElement.style.zIndex = 1000;
        activeTouchElement.style.width = rect.width + 'px';
        activeTouchElement.classList.add('dragging');
        
        document.body.appendChild(activeTouchElement); // Move to body to float over everything
        moveElement(touch.clientX, touch.clientY);
    }

    function handleTouchMove(e) {
        if(!activeTouchElement) return;
        e.preventDefault();
        const touch = e.touches[0];
        moveElement(touch.clientX, touch.clientY);
    }

    function moveElement(x, y) {
        activeTouchElement.style.left = (x - touchOffsetX) + 'px';
        activeTouchElement.style.top = (y - touchOffsetY) + 'px';
    }

    function handleTouchEnd(e) {
        if(!activeTouchElement) return;
        activeTouchElement.classList.remove('dragging');
        activeTouchElement.style.position = '';
        activeTouchElement.style.zIndex = '';
        activeTouchElement.style.width = '';
        activeTouchElement.style.left = '';
        activeTouchElement.style.top = '';

        // Check drop
        const touch = e.changedTouches[0];
        activeTouchElement.style.display = 'none'; // hide to find element below
        let elemBelow = document.elementFromPoint(touch.clientX, touch.clientY);
        activeTouchElement.style.display = '';

        const dropZone = elemBelow ? elemBelow.closest('.drop-zone') : null;
        
        if(dropZone && container.contains(dropZone)) {
            dropZone.appendChild(activeTouchElement);
        } else {
            originalParent.appendChild(activeTouchElement); // return to start
        }
        activeTouchElement = null;
    }
}

function checkDragDrop(containerId) {
    const container = document.getElementById(containerId);
    let correctCount = 0;
    let totalItems = 0;

    const zones = container.querySelectorAll('.drop-zone');
    zones.forEach(zone => {
        const expected = zone.dataset.zone;
        const items = zone.querySelectorAll('.draggable-item');
        
        items.forEach(item => {
            totalItems++;
            if(item.dataset.target === expected) {
                correctCount++;
                item.classList.add('correct');
            } else {
                item.classList.add('wrong');
            }
        });
    });
    
    // Also count unplaced items if they should be placed? 
    // Usually all items should be distributed.
    // Let's assume total items is ALL items in the container.
    const allItems = container.querySelectorAll('.draggable-item').length;
    
    // If items are left in source, they are incomplete or wrong? 
    // Let's stick to what's placed.
    
    if (correctCount === allItems && allItems > 0) {
        showFeedback(`feedback-${containerId}`, true, "عمل رائع! كل العناصر في مكانها الصحيح.");
    } else {
        showFeedback(`feedback-${containerId}`, false, "هناك بعض الأخطاء، حاول مرة أخرى.");
    }
}


