// MEMORY GAME
// ==========================================
/*
Expected HTML Structure:
<div id="game1" class="activity-container memory-game">
  <div class="memory-grid">
     <!-- Cards generated by JS or static -->
     <div class="memory-card" data-val="1">...front/back...</div>
     <div class="memory-card" data-val="1">...</div>
  </div>
</div>
*/

function initMemoryGame(containerId) {
  const container = document.getElementById(containerId);
  if (!container) return;
  
  const cards = Array.from(container.querySelectorAll('.memory-card'));
  let hasFlippedCard = false;
  let lockBoard = false;
  let firstCard, secondCard;
  let matches = 0;
  const totalPairs = cards.length / 2;

  function flipCard() {
    if (lockBoard) return;
    if (this === firstCard) return;

    this.classList.add('flipped');

    if (!hasFlippedCard) {
      hasFlippedCard = true;
      firstCard = this;
      return;
    }

    secondCard = this;
    checkForMatch();
  }

  function checkForMatch() {
    let isMatch = firstCard.dataset.val === secondCard.dataset.val;
    isMatch ? disableCards() : unflipCards();
  }

  function disableCards() {
    firstCard.removeEventListener('click', flipCard);
    secondCard.removeEventListener('click', flipCard);
    firstCard.classList.add('matched');
    secondCard.classList.add('matched');
    resetBoard();
    matches++;
    if(matches === totalPairs) {
        showFeedback(`feedback-${containerId}`, true, "ممتاز! لقد وجدت جميع الأزواج.");
    }
  }

  function unflipCards() {
    lockBoard = true;
    setTimeout(() => {
      firstCard.classList.remove('flipped');
      secondCard.classList.remove('flipped');
      resetBoard();
    }, 1000);
  }

  function resetBoard() {
    [hasFlippedCard, lockBoard] = [false, false];
    [firstCard, secondCard] = [null, null];
  }

  // Shuffle
  const grid = container.querySelector('.memory-grid');
  if(grid) {
      cards.forEach(card => {
        let randomPos = Math.floor(Math.random() * cards.length);
        card.style.order = randomPos;
        card.addEventListener('click', flipCard);
      });
  }
}


